#!/usr/bin/env python3
"""Breeding Value Ranker, Phase 1.

  python bvr.py template                      make a blank data workbook
  python bvr.py run data/breeding_data.xlsx   rank stallions and run the backtest
  python bvr.py export-web                    build the interactive page (docs/index.html)
  python bvr.py synth --scenario planted      make a labeled synthetic workbook
  python bvr.py power                         how often the backtest passes on synthetic data
"""
import argparse
import os
import sys

from ranker.core import Params, backtest, rank_stallions, truth_correlation
from ranker import synth, web, workbook


def cmd_template(a):
    if os.path.exists(a.out) and not a.force:
        sys.exit("%s already exists. Not overwriting it. Use --force, or pick another --out." % a.out)
    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    workbook.build_workbook().save(a.out)
    print("Wrote", a.out)


def _is_synthetic(path):
    from openpyxl import load_workbook
    wb = load_workbook(path, read_only=True)
    try:
        first = wb["README"].cell(row=1, column=1).value if "README" in wb.sheetnames else ""
    finally:
        wb.close()
    return str(first or "").upper().startswith("SYNTHETIC")


def cmd_run(a):
    ds, review, info = workbook.load(a.workbook)
    p = Params(min_foals=a.min_foals, top_k=a.top_k, mare_adjust=not a.no_dam_adjust,
               fee_fallback=a.fee_fallback, fee_basis=a.fee_basis, maturity_years=a.maturity,
               seed=a.seed)
    bt = backtest(ds, p, a.asof)
    ranked, skipped, fit = rank_stallions(ds, None, p, bt["final"])
    out = a.out or a.workbook.replace(".xlsx", "_results.xlsx")
    if os.path.abspath(out) == os.path.abspath(a.workbook):
        sys.exit("--out must differ from the input workbook.")
    workbook.write_results(a.workbook, out, ds, ranked, skipped, fit, bt, review, info, p,
                           synthetic=_is_synthetic(a.workbook))

    v = bt["verdict"]
    print("Stallions %d | foals linked %d | outcome rows %d | rows to review %d"
          % (len(ds.stallions), len(ds.foals), len(ds.outcomes), len(review)))
    print("Ranked today: %d stallions (%d not ranked)" % (len(ranked), len(skipped)))
    for r in ranked[:10]:
        print("  %2d. %-26s fee $%-6.0f foals %-4d effect %+5.1f (+/- %.1f)  per $1,000: %+.2f"
              % (r["rank"], r["name"], r["fee"], r["n"], r["effect"], r["se"], r["value_per_1k"]))
    print("Backtest windows:", ", ".join(str(w["asof"]) for w in bt["windows"]) or "none")
    print("Verdict: %s. %s" % (v["status"], v["why"]))
    for w in info["warnings"]:
        print("Warning:", w)
    print("Wrote", out)


def cmd_synth(a):
    ds = synth.generate(a.scenario, seed=a.seed, foals_per_year=a.foals_per_year,
                        sire_share=a.sire_share)
    out = a.out or "synthetic/synthetic_%s.xlsx" % a.scenario
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    banner = ("SYNTHETIC DATA, scenario '%s', seed %d. These horses do not exist. "
              "Generated by bvr.py to test the pipeline." % (a.scenario, a.seed))
    workbook.write_dataset(ds, out, banner)
    print("Wrote %s (%d stallions, %d foals, %d outcome rows)"
          % (out, len(ds.stallions), len(ds.foals), len(ds.outcomes)))


def cmd_export_web(a):
    p = Params(min_foals=a.min_foals, mare_adjust=not a.no_dam_adjust, fee_fallback=a.fee_fallback,
               fee_basis=a.fee_basis)
    data, size = web.export(a.workbook, a.out, repo_url=a.repo, params=p)
    print("Wrote %s (%d KB): %d stallions, %d fee rows, %d ranked, backtest %s"
          % (a.out, size // 1024, len(data["stallions"]),
             sum(len(s["fees"]) for s in data["stallions"]), len(data["real"]["ranking"]),
             data["real"]["verdict"]["status"]))


def cmd_power(a):
    print("%-11s %-10s %-12s %-12s %-10s %6s %6s %10s %10s"
          % ("scenario", "sire share", "foals/yr", "foals/sire", "dam adj", "PASS", "FAIL",
             "corr truth", "avg pctile"))

    def show(r):
        print("%-11s %-10.2f %-12.0f %-12.0f %-10s %5.0f%% %5.0f%% %10s %10.0f"
              % (r["scenario"], r["sire_share"], r["foals_per_stallion_year"],
                 r["avg_foals_per_stallion"], "on" if r["mare_adjust"] else "off",
                 100 * r["pass_rate"], 100 * r["fail_rate"],
                 "n/a" if r["corr_with_truth"] is None else "%.2f" % r["corr_with_truth"],
                 r["avg_random_percentile"]), flush=True)
    synth.power_table(reps=a.reps, progress=show)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    t = sub.add_parser("template", help="write a blank data workbook")
    t.add_argument("--out", default="data/breeding_data.xlsx")
    t.add_argument("--force", action="store_true", help="overwrite an existing file")
    t.set_defaults(fn=cmd_template)

    r = sub.add_parser("run", help="rank stallions and backtest")
    r.add_argument("workbook")
    r.add_argument("--asof", type=int, nargs="+", help="backtest as-of years (default: chosen automatically)")
    r.add_argument("--out", help="results workbook (default: <input>_results.xlsx)")
    r.add_argument("--min-foals", type=int, default=5, help="scored foals needed to rank a stallion")
    r.add_argument("--top-k", type=int, help="number of top picks per window (default: top quarter, at least 3)")
    r.add_argument("--no-dam-adjust", action="store_true", help="do not adjust for dam quality")
    r.add_argument("--fee-fallback", choices=("none", "latest"), default="none",
                   help="'latest' prices every past date with the newest fee on file (hindsight)")
    r.add_argument("--fee-basis", choices=("listed", "auction", "any"), default="listed",
                   help="'listed' uses advertised fees; 'auction' uses winning bids at "
                        "stallion-service auctions instead; 'any' takes whichever is newest")
    r.add_argument("--maturity", type=int, default=3,
                   help="age in years at which a lifetime-only total is trusted in the backtest")
    r.add_argument("--seed", type=int, default=7)
    r.set_defaults(fn=cmd_run)

    s = sub.add_parser("synth", help="write a synthetic workbook")
    s.add_argument("--scenario", choices=synth.SCENARIOS, default="planted")
    s.add_argument("--seed", type=int, default=1)
    s.add_argument("--foals-per-year", type=float, default=10.0)
    s.add_argument("--sire-share", type=float, default=0.08)
    s.add_argument("--out")
    s.set_defaults(fn=cmd_synth)

    w = sub.add_parser("export-web", help="build the interactive page in docs/index.html")
    w.add_argument("workbook", nargs="?", default="data/breeding_data.xlsx")
    w.add_argument("--out", default="docs/index.html")
    w.add_argument("--repo", default="", help="repository URL shown in the page footer")
    w.add_argument("--min-foals", type=int, default=5)
    w.add_argument("--no-dam-adjust", action="store_true")
    w.add_argument("--fee-fallback", choices=("none", "latest"), default="none")
    w.add_argument("--fee-basis", choices=("listed", "auction", "any"), default="listed")
    w.set_defaults(fn=cmd_export_web)

    pw = sub.add_parser("power", help="pass rates on synthetic data")
    pw.add_argument("--reps", type=int, default=100)
    pw.set_defaults(fn=cmd_power)

    a = ap.parse_args()
    a.fn(a)


if __name__ == "__main__":
    main()
